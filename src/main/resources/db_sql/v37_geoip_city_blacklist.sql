CREATE TABLE IF NOT EXISTS public.geoip_city_blacklist_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code VARCHAR(2) NOT NULL,
    province VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    ipv4_cidr_count INTEGER NOT NULL DEFAULT 0,
    ipv6_cidr_count INTEGER NOT NULL DEFAULT 0,
    last_generated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT,
    updated_by BIGINT,
    CONSTRAINT geoip_city_blacklist_entries_location_key
        UNIQUE (country_code, province, city)
);

CREATE INDEX IF NOT EXISTS geoip_city_blacklist_entries_enabled_idx
    ON public.geoip_city_blacklist_entries (enabled, id);
