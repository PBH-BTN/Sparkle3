-- Configuration values are imported from the bundled and external application YAML
-- by DatabaseConfigMigrationService. This migration creates durable target storage
-- and marks business settings as hot-reloadable without replacing production values
-- with hard-coded SQL defaults.
CREATE TABLE IF NOT EXISTS public.github_sync_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    repository_owner VARCHAR(100) NOT NULL,
    repository_name VARCHAR(100) NOT NULL,
    branch_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(1024) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_attempt_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT,
    last_commit_sha VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    updated_by BIGINT,
    CONSTRAINT github_sync_targets_file_unique
        UNIQUE (repository_owner, repository_name, branch_name, file_path)
);

CREATE TABLE IF NOT EXISTS public.github_sync_target_sources (
    target_id BIGINT NOT NULL
        REFERENCES public.github_sync_targets(id) ON DELETE CASCADE,
    source_id VARCHAR(128) NOT NULL,
    PRIMARY KEY (target_id, source_id)
);

CREATE INDEX IF NOT EXISTS github_sync_targets_enabled_idx
    ON public.github_sync_targets (enabled, name);

CREATE INDEX IF NOT EXISTS github_sync_target_sources_source_idx
    ON public.github_sync_target_sources (source_id);

