-- Sparkle3 schema snapshot for a brand-new database.
--
-- Existing installations are adopted by FlywayMigrationConfig and baselined at
-- the latest schema version they contain, so this destructive "create from
-- empty" migration is never run against a production schema with data.

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS timescaledb;

