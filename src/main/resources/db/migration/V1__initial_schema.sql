CREATE MATERIALIZED VIEW mv_overdownload_hourly_stats AS
SELECT
    date_trunc('hour', last_time_seen) AS analysis_hour,
    peer_ip,
    torrent_id,
    SUM(from_peer_traffic) AS total_downloaded,
    SUM(to_peer_traffic) AS total_uploaded,
    SUM(to_peer_traffic) - SUM(from_peer_traffic) AS pure_upload,
    COUNT(*) AS record_count,
    MAX(last_time_seen) AS last_seen,
    MIN(first_time_seen) AS first_seen
FROM swarm_tracker
WHERE (to_peer_traffic - from_peer_traffic) > 0
  AND last_time_seen >= NOW() - INTERVAL '30 days'
GROUP BY date_trunc('hour', last_time_seen), peer_ip, torrent_id
WITH DATA;

CREATE UNIQUE INDEX mv_overdownload_hourly_stats_pkey
    ON mv_overdownload_hourly_stats (analysis_hour, peer_ip, torrent_id);
CREATE INDEX mv_overdownload_hourly_stats_time_upload_idx
    ON mv_overdownload_hourly_stats (analysis_hour DESC, pure_upload DESC);
CREATE INDEX mv_overdownload_hourly_stats_peer_ip_idx
    ON mv_overdownload_hourly_stats (peer_ip, analysis_hour DESC);
CREATE INDEX mv_overdownload_hourly_stats_torrent_idx
    ON mv_overdownload_hourly_stats (torrent_id, analysis_hour DESC);

CREATE MATERIALIZED VIEW analyse_ban_history_hourly_basic
WITH (timescaledb.continuous) AS
SELECT
    time_bucket(INTERVAL '1 hour', populate_time) AS bucket,
    COUNT(*) AS total_bans,
    SUM(to_peer_traffic) AS total_to_peer_traffic,
    SUM(from_peer_traffic) AS total_from_peer_traffic
FROM ban_history
GROUP BY bucket
WITH NO DATA;

ALTER MATERIALIZED VIEW analyse_ban_history_hourly_basic SET (
    timescaledb.compress = TRUE
);

SELECT add_continuous_aggregate_policy(
    'analyse_ban_history_hourly_basic',
    start_offset => INTERVAL '3 days',
    end_offset => INTERVAL '1 hour',
    schedule_interval => INTERVAL '1 hour',
    if_not_exists => TRUE
);

CREATE MATERIALIZED VIEW analyse_ban_history_daily_base
WITH (timescaledb.continuous) AS
SELECT
    time_bucket(INTERVAL '1 day', populate_time) AS bucket,
    peer_client_name,
    peer_id,
    CASE
        WHEN family(peer_ip) = 4 THEN set_masklen(peer_ip::cidr, 24)
        WHEN family(peer_ip) = 6 THEN set_masklen(peer_ip::cidr, 52)
    END AS peer_ip_cidr,
    torrent_id,
    module_name,
    userapps_id,
    COUNT(*) AS ban_count,
    SUM(to_peer_traffic) AS total_to_peer_traffic,
    SUM(from_peer_traffic) AS total_from_peer_traffic
FROM ban_history
GROUP BY bucket, peer_client_name, peer_id, peer_ip_cidr, torrent_id, module_name, userapps_id
WITH NO DATA;

ALTER MATERIALIZED VIEW analyse_ban_history_daily_base SET (
    timescaledb.compress = TRUE
);

SELECT add_continuous_aggregate_policy(
    'analyse_ban_history_daily_base',
    start_offset => INTERVAL '3 days',
    end_offset => INTERVAL '1 hour',
    schedule_interval => INTERVAL '1 day',
    if_not_exists => TRUE
);

CREATE VIEW analyse_ban_history_daily_report AS
WITH
daily_summary AS (
    SELECT
        bucket,
        SUM(ban_count) AS total_ban_count,
        SUM(total_to_peer_traffic) AS total_to_peer_traffic,
        SUM(total_from_peer_traffic) AS total_from_peer_traffic
    FROM analyse_ban_history_daily_base
    GROUP BY bucket
),
top_client AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        peer_client_name AS top_peer_client_name
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, peer_client_name
    ORDER BY bucket, SUM(ban_count) DESC
),
top_peer AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        peer_id AS top_peer_id
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, peer_id
    ORDER BY bucket, SUM(ban_count) DESC
),
top_ip AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        peer_ip_cidr AS top_peer_ip_cidr
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, peer_ip_cidr
    ORDER BY bucket, SUM(ban_count) DESC
),
top_torrent AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        torrent_id AS top_torrent_id
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, torrent_id
    ORDER BY bucket, SUM(ban_count) DESC
),
top_module AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        module_name AS top_module_name
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, module_name
    ORDER BY bucket, SUM(ban_count) DESC
),
top_userapp AS (
    SELECT DISTINCT ON (bucket)
        bucket,
        userapps_id AS top_userapps_id
    FROM analyse_ban_history_daily_base
    GROUP BY bucket, userapps_id
    ORDER BY bucket, SUM(total_to_peer_traffic + total_from_peer_traffic) DESC
)
SELECT
    s.bucket AS date,
    s.total_ban_count,
    s.total_to_peer_traffic,
    s.total_from_peer_traffic,
    c.top_peer_client_name,
    p.top_peer_id,
    t_ip.top_peer_ip_cidr,
    t.top_torrent_id,
    m.top_module_name,
    u.top_userapps_id
FROM daily_summary s
LEFT JOIN top_client c ON s.bucket = c.bucket
LEFT JOIN top_peer p ON s.bucket = p.bucket
LEFT JOIN top_ip t_ip ON s.bucket = t_ip.bucket
LEFT JOIN top_torrent t ON s.bucket = t.bucket
LEFT JOIN top_module m ON s.bucket = m.bucket
LEFT JOIN top_userapp u ON s.bucket = u.bucket;
